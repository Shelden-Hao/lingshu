/**
 * One-off rebrand rewriter: lingshu -> lingshu.
 *
 * Applies explicit, ordered replacements (package scope, environment prefix, config directory)
 * to every text file outside node_modules/.git/dist, and reports what it touched.
 *
 * Usage: node scripts/rebrand-lingshu.mjs [--dry-run]
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const DRY_RUN = process.argv.includes("--dry-run");
const SKIP_DIRS = new Set(["node_modules", ".git", "dist", ".artifacts", "coverage", ".workbuddy"]);

/** Files we rewrite. Anything else (binaries, images, lockfiles handled separately) is skipped. */
const TEXT_EXTENSIONS = new Set([
	".ts",
	".tsx",
	".js",
	".mjs",
	".cjs",
	".json",
	".md",
	".sh",
	".html",
	".css",
	".yml",
	".yaml",
	".toml",
]);

/** Lockfiles and generated install locks are regenerated by npm, not hand-edited. */
const SKIP_FILES = new Set(["package-lock.json", "pnpm-lock.yaml", "install-lock.json"]);

const SCRIPTS = [
	// 1. Internal package scope. Ordered from longest to shortest so the lingshu-* names win first.
	["@lingshu/coding-agent", "@lingshu/coding-agent"],
	["@lingshu/agent-core", "@lingshu/agent-core"],
	["@lingshu/codemode", "@lingshu/codemode"],
	["@lingshu/durable", "@lingshu/durable"],
	["@lingshu/telemetry", "@lingshu/telemetry"],
	["@lingshu/schema", "@lingshu/schema"],
	["@lingshu/evals", "@lingshu/evals"],
	["@lingshu/ai", "@lingshu/ai"],
	["@lingshu/env", "@lingshu/env"],
	["@lingshu/mcp", "@lingshu/mcp"],
	["@lingshu/tui", "@lingshu/tui"],
	["@lingshu/chord", "@lingshu/chord"],
	["@lingshu/p3", "@lingshu/p3"],
	["@lingshu/", "@lingshu/"],
	// 2. Config directory. Only as a path segment or quoted literal, never as a file extension.
	[/(^|[^\w.])\.lingshu(?=\/|["'`,\s)]|$)/gm, "$1.lingshu"],
	// 3. Environment prefix. PI_BUNDLED_NODE is an esbuild define, not an env var.
	[/\bPI_(?!BUNDLED_NODE\b)([A-Z0-9_]+)/g, "LINGSHU_$1"],
];

const counts = new Map();
let touched = 0;

function rewrite(content) {
	let next = content;
	for (const [from, to] of SCRIPTS) {
		next = typeof from === "string" ? next.split(from).join(to) : next.replace(from, to);
	}
	return next;
}

function walk(dir) {
	for (const entry of readdirSync(dir)) {
		if (SKIP_DIRS.has(entry)) continue;
		const full = join(dir, entry);
		const stats = statSync(full);
		if (stats.isDirectory()) {
			walk(full);
			continue;
		}
		if (SKIP_FILES.has(entry) || !TEXT_EXTENSIONS.has(extname(entry))) continue;

		const before = readFileSync(full, "utf8");
		const after = rewrite(before);
		if (after === before) continue;

		touched++;
		for (const [from, to] of SCRIPTS) {
			const label = typeof from === "string" ? from : String(from);
			const hits = typeof from === "string" ? before.split(from).length - 1 : (before.match(from) ?? []).length;
			if (hits > 0) counts.set(label, (counts.get(label) ?? 0) + hits);
		}
		if (!DRY_RUN) writeFileSync(full, after, "utf8");
	}
}

walk(ROOT);

console.log(`${DRY_RUN ? "[dry-run] " : ""}rewrote ${touched} files under ${relative(process.cwd(), ROOT) || "."}`);
for (const [label, hits] of [...counts].sort((a, b) => b[1] - a[1])) {
	console.log(`  ${hits.toString().padStart(6)}  ${label}`);
}
